import { createHash } from 'node:crypto'
import { readdir, readFile, mkdir, writeFile } from 'node:fs/promises'
import { dirname, join, relative, resolve, sep } from 'node:path'
import { fileURLToPath } from 'node:url'
import JSZip from 'jszip'

const CATALOG_FORMAT = 'bandal-plugin-catalog'
const FIXED_MTIME = new Date('1980-01-01T00:00:00.000Z')
const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url))
const REPO_ROOT = resolve(SCRIPT_DIR, '..')
const EXAMPLES_DIR = join(REPO_ROOT, 'examples', 'plugins')
const DEFAULT_OUT = resolve(REPO_ROOT, '..', 'bandal-web', 'public', 'plugins')

function outputDirectory(argv) {
  const outIndex = argv.indexOf('--out')
  if (outIndex === -1) return DEFAULT_OUT
  const value = argv[outIndex + 1]
  if (value === undefined || value.startsWith('--')) {
    throw new Error('--out 뒤에 출력 폴더가 필요합니다.')
  }
  return resolve(process.cwd(), value)
}

async function filesBelow(root) {
  const files = []
  async function walk(directory) {
    for (const entry of await readdir(directory, { withFileTypes: true })) {
      const absolute = join(directory, entry.name)
      if (entry.isSymbolicLink()) {
        throw new Error(`심볼릭 링크는 패키징할 수 없습니다: ${absolute}`)
      }
      if (entry.isDirectory()) await walk(absolute)
      else if (entry.isFile()) files.push(absolute)
    }
  }
  await walk(root)
  return files.sort()
}

function relativeZipPath(root, absolute) {
  return relative(root, absolute).split(sep).join('/')
}

async function zipPlugin(directory) {
  const zip = new JSZip()
  for (const absolute of await filesBelow(directory)) {
    zip.file(relativeZipPath(directory, absolute), await readFile(absolute), {
      date: FIXED_MTIME,
      createFolders: false,
      unixPermissions: 0o100644
    })
  }
  return zip.generateAsync({
    type: 'nodebuffer',
    compression: 'DEFLATE',
    compressionOptions: { level: 9 },
    platform: 'UNIX',
    streamFiles: false
  })
}

function stringOrEmpty(value) {
  return typeof value === 'string' ? value : ''
}

function tagsOrEmpty(value) {
  return Array.isArray(value) && value.every((tag) => typeof tag === 'string')
    ? value
    : []
}

async function buildEntry(directory, out) {
  const manifest = JSON.parse(await readFile(join(directory, 'manifest.json'), 'utf8'))
  const id = stringOrEmpty(manifest.id)
  const version = stringOrEmpty(manifest.version)
  if (id === '' || version === '') {
    throw new Error(`${directory}/manifest.json에 id와 version이 필요합니다.`)
  }
  const fileName = `${id}-${version}.zip`
  const artifact = await zipPlugin(directory)
  await writeFile(join(out, fileName), artifact)
  return {
    id,
    kind: 'extension',
    name: stringOrEmpty(manifest.name),
    publisher: 'bandal',
    description: stringOrEmpty(manifest.description),
    tags: tagsOrEmpty(manifest.tags),
    version,
    minAppVersion: stringOrEmpty(manifest.minAppVersion),
    url: fileName,
    sha256: createHash('sha256').update(artifact).digest('hex')
  }
}

async function main() {
  const out = outputDirectory(process.argv.slice(2))
  await mkdir(out, { recursive: true })
  const directories = (await readdir(EXAMPLES_DIR, { withFileTypes: true }))
    .filter((entry) => entry.isDirectory() && entry.name !== '_fixtures')
    .map((entry) => join(EXAMPLES_DIR, entry.name))
    .sort()
  const entries = await Promise.all(
    directories.map((directory) => buildEntry(directory, out))
  )
  entries.sort(
    (left, right) =>
      (left.id < right.id ? -1 : left.id > right.id ? 1 : 0) ||
      (left.version < right.version ? -1 : left.version > right.version ? 1 : 0)
  )
  const index = {
    format: CATALOG_FORMAT,
    version: 1,
    name: '반달 공식',
    entries
  }
  await writeFile(join(out, 'index.json'), `${JSON.stringify(index, null, 2)}\n`)
  await writeFile(join(out, 'README.md'), '<!-- Generated by bandal/scripts/build-plugin-catalog.mjs. -->\n')
}

await main()
